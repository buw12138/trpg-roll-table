/* ============================================================
 * 17a. 规则速查「规则包格式规范」：文档本体 + 工具内查看 + 示例下载
 *     文档用 Markdown 写，工具里用 07-md 渲染，同时可导出为 .md
 * ============================================================ */
(function (RT) {
  'use strict';

  const SPEC = [
    '# 规则包格式规范',
    '',
    '这份文档说明「速查」页能吃下什么格式。照着做，导入即可用；写错了也能从文末的「常见错误」里对号入座。',
    '',
    '## 一、两种格式',
    '',
    '| 格式 | 扩展名 | 适合谁 | 特点 |',
    '| --- | --- | --- | --- |',
    '| Markdown | `.md` / `.markdown` / `.txt` | 大多数人 | 手写最省事；导入后可再导出成 `.md` |',
    '| JSON | `.json` | 想精确控制结构、想一次导入多个包 | 用 blocks 描述结构；不支持导出回 `.md` |',
    '',
    '两种都能拖进导入框、粘贴、或点「选择文件」。',
    '',
    '## 二、Markdown 写法',
    '',
    '支持下面这些语法，其它语法会被当成普通文字。',
    '',
    '| 写法 | 效果 | 说明 |',
    '| --- | --- | --- |',
    '| `# 标题` | 一级标题 | 自动进左侧目录 |',
    '| `## 标题` | 二级标题 | 自动进目录，建议当作「章」 |',
    '| `### 标题` | 三级标题 | 自动进目录 |',
    '| `#### 标题` | 四级标题 | 只显示，不进目录 |',
    '| `- 条目` 或 `* 条目` | 无序列表 | 不支持嵌套，缩进也会被忽略 |',
    '| `1. 条目` | 有序列表 | 数字不连续也会按顺序显示 |',
    '| `**粗体**` | 加粗 | 可嵌在段落、表格、列表里 |',
    '| `*斜体*` | 斜体 | 行内单个星号 |',
    '| 反引号包起来的文字 | 等宽 | 适合写 DC、骰式、技能名 |',
    '| `[文字](https://…)` | 链接 | 只认 http/https，新窗口打开 |',
    '| `> 引用` | 引用块 | 适合写「注意」「官方原文」 |',
    '| `---` 单独一行 | 分隔线 | 前后要空行 |',
    '| 三个反引号包起来的代码块 | 预格式块 | 适合粘整段表格原文 |',
    '',
    '### 表格',
    '',
    '表头下一行必须是分隔行，用 `|` 与 `---` 组成：',
    '',
    '| 难度 | DC |',
    '| --- | --- |',
    '| 简单 | 10 |',
    '| 中等 | 15 |',
    '',
    '列数按表头算；列宽由浏览器自动分配，不用写对齐冒号（写了也忽略）。',
    '',
    '### 不支持的写法',
    '',
    '- 嵌套列表（`-` 下面再缩进 `-`）：会拍平成同一层',
    '- 图片 `![](…)`：不解析，原样显示文字',
    '- HTML 标签：按纯文本显示，不会执行',
    '- 任务列表 `- [ ] 待办`：按普通文字显示',
    '- Setext 标题（用 `===` 下划线做标题）：不支持，请用 `#`',
    '- 脚注、定义列表、数学公式：不支持',
    '',
    '## 三、JSON 写法',
    '',
    'JSON 有三种可接受的形状，任选一种。',
    '',
    '### 形状 A：一个包，正文用 Markdown',
    '',
    '```json',
    '{',
    '  "name": "我的规则包",',
    '  "source": "自制",',
    '  "md": "# 我的规则包\\n\\n## 判定\\n\\n- 说出目标与难度"',
    '}',
    '```',
    '',
    '### 形状 B：一个包，正文用结构化 blocks',
    '',
    '```json',
    '{',
    '  "name": "我的规则包",',
    '  "blocks": [',
    '    { "t": "h", "level": 1, "text": "我的规则包" },',
    '    { "t": "h", "level": 2, "text": "判定" },',
    '    { "t": "ul", "items": ["说出目标与难度", "玩家掷 2d6 加属性"] }',
    '  ]',
    '}',
    '```',
    '',
    '### 形状 C：一次导入多个包',
    '',
    '```json',
    '{ "packs": [',
    '  { "name": "包一", "md": "# 包一\\n\\n正文" },',
    '  { "name": "包二", "blocks": [{ "t": "p", "text": "正文" }] }',
    '] }',
    '```',
    '',
    '### JSON 字段说明',
    '',
    '| 字段 | 必填 | 说明 |',
    '| --- | --- | --- |',
    '| `name` | 是 | 规则包名称，左侧列表与标题用它；留空会退回「导入的规则包」 |',
    '| `md` | 二选一 | Markdown 正文；`\\n` 表示换行 |',
    '| `blocks` | 二选一 | 结构化正文，类型见下表 |',
    '| `source` | 否 | 来源备注，显示在标题下方（如「5E 官方」「自制」） |',
    '',
    '`md` 与 `blocks` 都给时，**`md` 优先**。',
    '',
    '### blocks 类型',
    '',
    '| `t` | 其它字段 | 效果 |',
    '| --- | --- | --- |',
    '| `h` | `level`（1–4）、`text` | 标题，1–3 级进目录 |',
    '| `p` | `text` | 段落 |',
    '| `ul` | `items`（字符串数组） | 无序列表 |',
    '| `ol` | `items`（字符串数组） | 有序列表 |',
    '| `table` | `head`（表头数组）、`rows`（二维数组） | 表格 |',
    '| `quote` | `text` | 引用块 |',
    '| `hr` | 无 | 分隔线 |',
    '| `code` | `text` | 预格式块 |',
    '',
    '行内格式（粗体、行内码、链接）在 `text`、`items`、`head`、`rows` 里都可用。',
    '',
    '## 四、命名与去重',
    '',
    '- 名称优先级：JSON 的 `name` → 文件名（去扩展名）→ 正文第一个一级标题 → 「导入的规则包」',
    '- 重名不会覆盖：后导入的会自动加「（导入）」「（导入 2）」',
    '- 想替换旧包：先在速查页删掉旧的，再导入新的',
    '',
    '## 五、目录与搜索',
    '',
    '- 左侧「目录」收录 1–3 级标题，点一下跳到对应位置',
    '- 搜索框会在正文里高亮命中词，并过滤目录；清空搜索即恢复',
    '- 标题尽量短：目录一行显示不下会省略，鼠标悬停可看全称',
    '',
    '## 六、体量与编码',
    '',
    '- 编码用 UTF-8；带 BOM 也能导入（工具会自动去掉）',
    '- 单个包建议不超过 200 KB 纯文本；所有本地数据共用浏览器约 5 MB 额度',
    '- 一个包只装一个系统或一本书的速查，比混装更好搜',
    '',
    '## 七、常见错误',
    '',
    '| 现象 | 原因 | 改法 |',
    '| --- | --- | --- |',
    '| 导入后正文一片文字 | 表格分隔行写错 | 表头下一行必须是 `| --- | --- |` 这种 |',
    '| 标题没进目录 | 用了 `####` 或 Setext 标题 | 改成 `#` / `##` / `###` |',
    '| 列表挤成一坨 | 用了嵌套列表或没空行 | 拍平成一层，列表前后各留一个空行 |',
    '| 粗体显示成星号 | 星号不成对 | 成对写 `**粗体**` |',
    '| 导入提示「JSON 解析失败」 | 用了中文引号或末尾多逗号 | 换成英文引号，删掉多余逗号 |',
    '| 名字变成「导入的规则包」 | JSON 里没有 `name`，正文也没有一级标题 | 补 `name` 或加一行 `# 标题` |',
    '',
    '## 八、最小示例（可直接导入）',
    '',
    'Markdown 版：',
    '',
    '```md',
    '# 我的房规速查',
    '',
    '## 判定',
    '',
    '- 需要判定时，说清「目标 + 难度」，让玩家掷。',
    '- 玩家主动描述的动作，优先判「能，而且有代价」。',
    '',
    '## 难度',
    '',
    '| 难度 | DC |',
    '| --- | --- |',
    '| 简单 | 10 |',
    '| 中等 | 15 |',
    '| 困难 | 20 |',
    '```',
    '',
    'JSON 版见「下载示例 .json」按钮里的文件，两个包分别演示 `md` 与 `blocks`。',
    '',
    '## 九、导入步骤',
    '',
    '1. 侧栏点「速查」',
    '2. 点「导入 / 粘贴内容」（或空状态里的按钮）',
    '3. 选文件、拖进文本框，或直接粘贴',
    '4. 名称留空则按上面的优先级取名；点「导入」',
    '5. 左侧出现新包，正文与目录即刻可用',
    '',
    '> 想改已有包：先在速查页「导出 .md」，改完删掉旧包再导入，避免同内容两份。',
  ].join('\n');

  const SAMPLE_MD = [
    '# 我的房规速查',
    '',
    '> 这是示例规则包，导进来看看效果，之后随意改或删。',
    '',
    '## 判定',
    '',
    '- 需要判定时，说清「目标 + 难度」，让玩家掷。',
    '- 玩家主动描述的动作，优先判「能，而且有代价」。',
    '- 描述比数值重要：先给画面，再给 DC。',
    '',
    '## 难度',
    '',
    '| 难度 | DC | 典型情形 |',
    '| --- | --- | --- |',
    '| 简单 | 10 | 有准备、有工具 |',
    '| 中等 | 15 | 需要一点运气 |',
    '| 困难 | 20 | 专业水准 |',
    '| 极难 | 25 | 传说级 |',
    '',
    '## 战斗',
    '',
    '- 一回合：移动 + 一个动作 + 一个附赠动作（可选）',
    '- 掩体：半掩体 +2，四分之三 +5，全掩体不可被选中',
    '- 说不清怪物打谁时，公开随机选，并说明理由',
    '',
    '### 伤害速记',
    '',
    '| 等级 | 小挫 | 危险 | 致命 |',
    '| --- | --- | --- | --- |',
    '| 1–4 | 5 (1d10) | 11 (2d10) | 22 (4d10) |',
    '| 5–10 | 11 (2d10) | 22 (4d10) | 55 (10d10) |',
    '',
    '## 备用条目',
    '',
    '- 行内码：`DC 15` 与 **加粗** 都能用',
    '- 链接示例：[示例站](https://example.com)',
    '',
    '---',
    '',
    '结尾段落：把这一段换成你自己的规则即可。',
  ].join('\n');

  const SAMPLE_JSON = JSON.stringify({
    packs: [
      {
        name: '示例 · Markdown 包',
        source: '格式示例',
        md: '# 示例 · Markdown 包\n\n## 判定\n\n- 说出目标与难度\n- 玩家掷 2d6 加属性\n\n| 难度 | 目标值 |\n| --- | --- |\n| 简单 | 10 |\n| 中等 | 15 |\n',
      },
      {
        name: '示例 · blocks 包',
        source: '格式示例',
        blocks: [
          { t: 'h', level: 1, text: '示例 · blocks 包' },
          { t: 'h', level: 2, text: '判定' },
          { t: 'ul', items: ['说出目标与难度', '玩家掷 2d6 加属性'] },
          { t: 'h', level: 2, text: '难度' },
          {
            t: 'table',
            head: ['难度', '目标值'],
            rows: [['简单', '10'], ['中等', '15'], ['困难', '20']],
          },
          { t: 'quote', text: '这一份用结构化 blocks 描述，效果与 Markdown 版一致。' },
        ],
      },
    ],
  }, null, 2);

  RT.rulesSpec = { md: SPEC, sampleMd: SAMPLE_MD, sampleJson: SAMPLE_JSON };

  RT.showRulesSpec = function () {
    const rendered = RT.md.render(SPEC);
    RT.dialogs.open({
      title: '规则包格式规范',
      wide: true,
      body:
        '<div class="spec-acts">' +
        '<button class="btn ghost small" id="spec-md">' + RT.icon('download', 13) + ' 下载示例 .md</button>' +
        '<button class="btn ghost small" id="spec-json">' + RT.icon('download', 13) + ' 下载示例 .json</button>' +
        '<button class="btn ghost small" id="spec-copy">' + RT.icon('copy', 13) + ' 复制规范全文</button>' +
        '</div>' +
        '<div class="rules-doc md spec-doc">' + rendered.html + '</div>',
      onMount: function (modal) {
        const mdBtn = modal.querySelector('#spec-md');
        const jsonBtn = modal.querySelector('#spec-json');
        const copyBtn = modal.querySelector('#spec-copy');
        if (mdBtn) {
          mdBtn.addEventListener('click', function () {
            RT.download('示例规则包-' + RT.dateStamp() + '.md', SAMPLE_MD, 'text/markdown');
          });
        }
        if (jsonBtn) {
          jsonBtn.addEventListener('click', function () {
            RT.download('示例规则包-' + RT.dateStamp() + '.json', SAMPLE_JSON);
          });
        }
        if (copyBtn) {
          copyBtn.addEventListener('click', function () { RT.copyText(SPEC); });
        }
      },
    });
  };

  RT.acts['rules-spec'] = function () {
    RT.showRulesSpec();
  };

})(window.RT = window.RT || {});
